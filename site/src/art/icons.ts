export type IconName = keyof typeof SMALL | keyof typeof LARGE;
export const ICONS: Readonly<Record<IconName, readonly string[]>> = { ...SMALL, ...LARGE };

/** The bitmap as one SVG path of horizontal runs. */
export function iconPath(rows: readonly string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    for (const match of row.matchAll(/#+/g)) d += `M${match.index} ${y}h${match[0].length}v1h-${match[0].length}z`;
  });
  return d;
}

/** Inline SVG for an icon. Decorative: the text next to it, or an aria-label, names it. */
export function iconSvg(name: IconName, className = ""): string {
  const rows = ICONS[name];
  const size = rows.length;
  return `<svg class="px-icon px-icon-${size === 8 ? "sm" : "lg"}${className ? ` ${className}` : ""}" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true" focusable="false"><path d="${iconPath(rows)}"/></svg>`;
}

export const isIconName = (name: string): name is IconName => Object.hasOwn(ICONS, name);
